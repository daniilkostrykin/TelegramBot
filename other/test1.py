def to_markdown(text):
    """
    Преобразует текст в формат Markdown для Telegram.
    - Заменяет маркеры списка
    - Сохраняет форматирование жирного текста (включая вложенный)
    - Экранирует специальные символы
    """
    # Сохраняем жирный текст
    bold_texts = []

    def save_bold(match):
        # Ищем вложенные жирные тексты внутри текущего
        inner_text = match.group(1)
        inner_text = re.sub(r'\*([^*]+)\*', r'*\1*', inner_text)
        bold_texts.append(inner_text)
        return f"§BOLD{len(bold_texts)-1}§"

    # Сохраняем математические выражения
    math_exprs = []

    def save_math(match):
        math_exprs.append(match.group(0))
        return f"§MATH{len(math_exprs)-1}§"

    # Сохраняем жирный текст (нежадное совпадение для вложенных **)
    text = re.sub(r'\*\*(.*?)\*\*', save_bold, text, flags=re.DOTALL)

    print("Найденный жирный текст:")
    for i, bold in enumerate(bold_texts):
        print(f"{i}: {bold}")

    # Сохраняем математические выражения (цифры с умножением)
    text = re.sub(r'\d+\s*\*\s*\d+', save_math, text)

    # Заменяем HTML-теги
    text = re.sub(r'<sup>([^<]+)</sup>', r'^\1', text)
    text = re.sub(r'<sub>([^<]+)</sub>', r'_\1', text)

    # Заменяем маркеры списка
    text = re.sub(r'^\s*\*\s+', '• ', text, flags=re.MULTILINE)

    # Экранируем специальные символы Markdown
    special_chars = '_*[]()~`>#+-=|{}.!\\'

    # Сначала экранируем все специальные символы в обычном тексте
    escaped_text = ''
    for char in text:
        if char in special_chars:
            escaped_text += f'\\{char}'
        else:
            escaped_text += char
    text = escaped_text

    # Возвращаем жирный текст
    for i, bold_text in enumerate(bold_texts):
        # Экранируем специальные символы внутри жирного текста, кроме *
        escaped_bold = ''
        for char in bold_text:
            if char in special_chars and char != '*':
                escaped_bold += f'\\{char}'
            else:
                escaped_bold += char
        # Заменяем маркер на жирный текст
        text = text.replace(f"§BOLD{i}§", f"*{escaped_bold}*")

    # Возвращаем математические выражения
    for i, math_expr in enumerate(math_exprs):
        # Заменяем умножение на экранированную звездочку
        escaped_expr = ''
        for char in math_expr:
            if char in special_chars:
                escaped_expr += f'\\{char}'
            else:
                escaped_expr += char
        text = text.replace(f"§MATH{i}§", escaped_expr)

    print("Результат форматирования:")
    print(text)

    return text


